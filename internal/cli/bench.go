func newBenchInfraCmd(app *App) *cobra.Command {
	var (
		modelName string
		opt       benchmark.InfraOptions
		sustained time.Duration
		outDir    string
		apply     bool
		onlyCfg   []string
	)
	cmd := &cobra.Command{
		Use:   "infra",
		Short: "Sweep inference-server settings and measure load, memory, prompt/decode speed and thermals",
		Long: `Finds, for each context size and KV cache type, the minimum number of MoE
layers that must stay in system RAM (n_cpu_moe) to fit in VRAM, then measures
nearby configurations with real requests. Results are written as JSON and
Markdown and recorded in the state database. With --apply the recommended
settings are saved as a user profile override.

This stops any managed llama-server and takes a long time (tens of minutes).`,
		RunE: func(cmd *cobra.Command, _ []string) error {
			if app.Config.Inference.Mode != "managed" {
				return fmt.Errorf("infra benchmarks need inference.mode: managed")
			}
			p, err := app.profile(modelName)
			if err != nil {
				return err
			}
			opt.Profile, opt.Sustained = p, sustained
			for _, c := range onlyCfg {
				var cf benchmark.Config
				if _, err := fmt.Sscanf(strings.ReplaceAll(c, ":", " "), "%d %s %d %d", &cf.CtxSize, &cf.CacheType, &cf.UBatch, &cf.NCPUMoE); err != nil {
					return fmt.Errorf("--config %q: want ctx:kv:ubatch:n_cpu_moe", c)
				}
				opt.Only = append(opt.Only, cf)
			}
			if err := os.MkdirAll(outDir, 0o755); err != nil {
				return err
			}
			stamp := time.Now().UTC().Format("20060102T150405Z")
			base := filepath.Join(outDir, fmt.Sprintf("%s-infra-%s", stamp, p.Name))
			opt.OutPath = base + ".json"
			runner := &benchmark.InfraRunner{Mgr: app.llamaManager(), Log: app.Log,
				Progress: func(s string) { fmt.Fprintf(app.Err, "%s %s\n", time.Now().Format("15:04:05"), s) }}
			rep, runErr := runner.Run(cmd.Context(), opt)
			var md bytes.Buffer
			if err := benchmark.WriteInfraMarkdown(&md, rep); err != nil {
				return err
			}
			if err := os.WriteFile(base+".md", md.Bytes(), 0o644); err != nil {
				return err
			}
			if err := recordBenchmark(cmd, app, rep.ID, "infra", p.Name, opt, rep); err != nil {
				return err
			}
			app.printf("report: %s.{json,md}\n", base)
			if runErr != nil {
				return runErr
			}
			if rep.Recommended == nil {
				return fmt.Errorf("no configuration met the constraints")
			}
			rc := rep.Recommended
			app.printf("recommended: ctx=%d kv=%s ubatch=%d n_cpu_moe=%d decode=%.1f t/s prompt=%.0f t/s\n",
				rc.CtxSize, rc.CacheType, rc.UBatch, rc.NCPUMoE, rc.DecodeTPS, rc.PromptTPS)
			if apply {
				np := p
				np.Server.CtxSize, np.Server.CacheTypeK, np.Server.CacheTypeV = rc.CtxSize, rc.CacheType, rc.CacheType
				np.Server.UBatchSize, np.Server.NCPUMoE = rc.UBatch, rc.NCPUMoE
				np.Server.BatchSize = max(np.Server.BatchSize, rc.UBatch)
				if np.Server.Parallel == 0 {
					np.Server.Parallel = 1
				}
				b, err := yaml.Marshal(np)
				if err != nil {
					return err
				}
				header := fmt.Sprintf("# Generated by `bench infra --apply` from report %s.\n", rep.ID)
				dst := filepath.Join(app.Paths.Config, "models", p.Name+".yaml")
				if err := config.WriteFileAtomic(dst, append([]byte(header), b...), 0o600); err != nil {
					return err
				}
				app.printf("applied to %s\n", dst)
			}
			return nil
		},
	}
	f := cmd.Flags()
	f.StringVarP(&modelName, "model", "m", "", "model profile")
	f.IntSliceVar(&opt.CtxSizes, "ctx", []int{32768, 65536}, "context sizes")
	f.StringSliceVar(&opt.CacheTypes, "kv", []string{"q8_0"}, "KV cache types (f16, q8_0, q4_0)")
	f.IntSliceVar(&opt.UBatches, "ubatch", []int{512}, "physical batch sizes")
	f.IntVar(&opt.MoESpan, "moe-span", 4, "measure n_cpu_moe from the minimum up to minimum+span (step 2)")
	f.IntVar(&opt.MoEMax, "moe-max", 40, "number of MoE layers in the model")
	f.IntSliceVar(&opt.PromptSizes, "prompt", []int{2048, 8192, 24576, 49152}, "prompt sizes in tokens")
	f.IntVar(&opt.DecodeTokens, "decode", 128, "tokens to generate per request")
	f.IntVar(&opt.MinFreeVRAMMiB, "min-free-vram", 300, "VRAM headroom (MiB) required for a recommendation")
	f.DurationVar(&sustained, "sustained", 0, "sustained decode run on the recommended config (e.g. 10m)")
	f.StringVar(&outDir, "out", "benchmarks/reports", "output directory")
	f.BoolVar(&apply, "apply", false, "save the recommended settings as a user profile override")
	f.StringSliceVar(&onlyCfg, "config", nil, "measure only these configs: ctx:kv:ubatch:n_cpu_moe (repeatable), skipping the search")
	f.BoolVar(&opt.ColdLoad, "cold", false, "evict the model from the page cache before each load (true cold-load times)")
	f.StringVar(&opt.Conditions, "conditions", "", "note about run conditions (e.g. \"idle, AC power\")")
	return cmd
}

func recordBenchmark(cmd *cobra.Command, app *App, id, kind, modelName string, cfg, result any) error {
	s, err := app.Store(cmd.Context())
	if err != nil {
		return err
	}
	cj, _ := json.Marshal(cfg)
	rj, _ := json.Marshal(result)
	mj, _ := json.Marshal(map[string]any{"hostname": hostname()})
	_, err = s.DB.ExecContext(cmd.Context(),
		`INSERT OR REPLACE INTO benchmark_runs(id, kind, model, config, result, machine, created_at) VALUES(?,?,?,?,?,?,?)`,
		id, kind, modelName, string(cj), string(rj), string(mj), store.Now())
	return err
}

func hostname() string {
	h, _ := os.Hostname()
	return h
}

func newBenchTasksCmd(app *App) *cobra.Command {
	var (
		dir, out, fixtures string
		screenGold         string
		baseline           bool
		only               []string
		rf                 runFlags
	)
	cmd := &cobra.Command{
		Use:   "tasks",
		Short: "Run the engineering benchmark suite (hidden acceptance checks) with the real agent",
		RunE: func(cmd *cobra.Command, _ []string) error {
			ctx := cmd.Context()
			tasks, err := benchmark.LoadTasks(dir)
			if err != nil {
				return err
			}
			if len(only) > 0 {
				var sel []benchmark.TaskSpec
				for _, t := range tasks {
					if contains(only, t.ID) || contains(only, t.Category) {
						sel = append(sel, t)
					}
				}
				tasks = sel
			}
			if len(tasks) == 0 {
				return fmt.Errorf("no tasks selected")
			}
			p, err := app.profile(rf.model)
			if err != nil {
				return err
			}
			sb, err := app.sandbox(rf.unsafeNoSandbox)
			if err != nil {
				return err
			}
			// Scratch space must be visible to the container engine (Docker
			// Desktop shares $HOME, not /tmp).
			work := filepath.Join(app.Paths.Cache, "bench-work")
			if err := os.MkdirAll(work, 0o700); err != nil {
				return err
			}
			stamp := time.Now().UTC().Format("20060102T150405Z")
			if screenGold != "" {
				res := benchmark.Screen(ctx, sb, fixtures, work, screenGold, tasks,
					func(s string) { fmt.Fprintf(app.Err, "%s %s\n", time.Now().Format("15:04:05"), s) })
				b, _ := json.MarshalIndent(res, "", "  ")
				if out == "" {
					app.printf("%s\n", b)
					return nil
				}
				return config.WriteFileAtomic(out, b, 0o644)
			}
			if out == "" {
				out = filepath.Join("benchmarks", "reports", fmt.Sprintf("%s-tasks-%s.json", stamp, p.Name))
			}
			sr := &benchmark.SuiteRunner{FixturesDir: fixtures, WorkRoot: work, Sandbox: sb,
				Model: modelPin(p), ServerBinary: app.serverBinary(), TaskDirs: []string{dir},
				Progress: func(s string) { fmt.Fprintf(app.Err, "%s %s\n", time.Now().Format("15:04:05"), s) },
				NewRunner: func(ctx context.Context, stateDir string) (*orchestrator.Runner, func(), error) {
					paths := config.Paths{Runtime: app.Paths.Runtime, Config: app.Paths.Config, Data: filepath.Join(stateDir, "data"), Cache: filepath.Join(stateDir, "cache"), State: filepath.Join(stateDir, "state")}
					if err := paths.Ensure(); err != nil {
						return nil, nil, err
					}
					st, err := store.Open(ctx, paths.StateDB())
					if err != nil {
						return nil, nil, err
					}
					r, cleanup, err := app.buildRunnerWith(ctx, rf, st.DB, paths)
					if err != nil {
						st.Close()
						return nil, nil, err
					}
					r.Out = app.Err
					return r, func() { cleanup(); st.Close() }, nil
				}}
			run := sr.Run
			if baseline {
				run = sr.RunBaselines
			}
			rep, err := run(ctx, p.Name, tasks, out)
			if rep != nil {
				md := strings.TrimSuffix(out, ".json") + ".md"
				var b bytes.Buffer
				_ = benchmark.WriteSuiteMarkdown(&b, rep)
				_ = os.WriteFile(md, b.Bytes(), 0o644)
				_ = recordBenchmark(cmd, app, rep.ID, "engineering", p.Name, map[string]any{"tasks": len(tasks)}, rep)
				s := rep.Summary
				app.printf("verified %d/%d (%.0f%%), local-only %.0f%%, escalation rate %.0f%%, %.1f verified/hour, %.0fs/task\nreport: %s\n",
					s.Verified, s.Tasks, 100*s.SuccessRate, 100*s.LocalOnlyRate, 100*s.FrontierEscalationRate, s.VerifiedPerHour, s.MeanWallSeconds, md)
			}
			return err
		},
	}
	f := cmd.Flags()
	f.StringVar(&dir, "tasks", "benchmarks/tasks", "task definitions directory")
	f.StringVar(&fixtures, "fixtures", "benchmarks/fixtures", "fixtures directory")
	f.StringSliceVar(&only, "only", nil, "task ids or categories to run")
	f.StringVar(&out, "out", "", "report path (.json; .md written alongside)")
	f.BoolVar(&baseline, "baseline", false, "run the plain agent runtime with the same model and no control plane (comparison baseline)")
	f.StringVar(&screenGold, "screen-gold", "", "validate tasks instead of running them: acceptance must fail on base and pass with DIR/<id>.patch applied")
	addRunFlags(cmd, &rf)
	return cmd
}

func newBenchDirectCmd(app *App) *cobra.Command {
	var (
		dirs                     []string
		out, fixtures, modelName string
		approval                 string
		only, compare            []string
		timeout                  time.Duration
		workingSet               int
		noHistoryNotes           bool
	)
	cmd := &cobra.Command{
		Use:   "direct",
		Short: "Run the everyday-development suite with the direct-mode agent (in the checkout, on this machine)",
		Long: `Each task is one message to a fresh direct-mode session in a copy of a
fixture, routed as the chat routes it, with bounded mode unavailable. Hidden
checks run in the checkout afterwards; a question is judged by what its
answer must say. The report records pass or fail, model calls, tool calls,
prompt tokens and the server's cache hits, generated tokens, results set
aside and recalled, summaries, broken edits caught by the check, and time.`,
		RunE: func(cmd *cobra.Command, _ []string) error {
			ctx := cmd.Context()
			if len(compare) > 0 {
				if len(compare) != 2 {
					return fmt.Errorf("--compare takes two report paths")
				}
				a, err := benchmark.LoadDirectReport(compare[0])
				if err != nil {
					return err
				}
				b, err := benchmark.LoadDirectReport(compare[1])
				if err != nil {
					return err
				}
				var buf bytes.Buffer
				benchmark.CompareDirect(&buf, a, b)
				app.printf("%s", buf.String())
				return nil
			}
			var tasks []benchmark.TaskSpec
			for _, d := range dirs {
				ts, err := benchmark.LoadTasks(d)
				if err != nil {
					return err
				}
				tasks = append(tasks, ts...)
			}
			if len(only) > 0 {
				var sel []benchmark.TaskSpec
				for _, t := range tasks {
					if contains(only, t.ID) || contains(only, t.Category) {
						sel = append(sel, t)
					}
				}
				tasks = sel
			}
			if len(tasks) == 0 {
				return fmt.Errorf("no tasks selected")
			}
			switch approval {
			case direct.ApprovalAsk, direct.ApprovalEdits, direct.ApprovalAuto:
			default:
				return fmt.Errorf("approval %q is not ask|edits|auto", approval)
			}
			ep, err := app.directEndpoint(ctx, modelName)
			if err != nil {
				return err
			}
			work := filepath.Join(app.Paths.Cache, "bench-direct")
			if err := os.MkdirAll(work, 0o700); err != nil {
				return err
			}
			stamp := time.Now().UTC().Format("20060102T150405Z")
			if out == "" {
				out = filepath.Join("benchmarks", "reports", fmt.Sprintf("%s-direct-%s.json", stamp, ep.model))
			}
			dc := app.Config.Direct
			if workingSet < 0 {
				return fmt.Errorf("--working-set must be positive")
			}
			if workingSet > 0 {
				dc.WorkingSetTokens = workingSet
			}
			if noHistoryNotes {
				off := false
				dc.HistoryNotes = &off
			}
			dr := &benchmark.DirectRunner{FixturesDir: fixtures, WorkRoot: work, Rules: app.riskRules(), Timeout: timeout,
				Tokenize: ep.tokenize, Model: ep.pin, TaskDirs: dirs,
				Settings: map[string]any{"approval": approval, "working_set_tokens": dc.WorkingSetTokens, "max_tool_output": dc.MaxToolOutput, "checks": dc.ChecksOn(), "seed_pack": dc.SeedPackOn(), "history_notes": dc.HistoryNotesOn(), "context_tokens": ep.ctxSize, "provider": ep.provider},
				Progress: func(s string) { fmt.Fprintf(app.Err, "%s %s\n", time.Now().Format("15:04:05"), s) },
				NewRunner: func(ctx context.Context, root, stateDir string) (*direct.Runner, func(), error) {
					sess, err := direct.NewSession(filepath.Join(stateDir, "sessions"), root, ep.provider, ep.model)
					if err != nil {
						return nil, nil, err
					}
					opts := app.directOptions(root, root, approval, ep.ctxSize)
					// A benchmark is the project and the model alone: no
					// personal instructions, notes, commands, hooks or servers.
					opts.UserInstructions, opts.MemoryFile, opts.UserDir = "", "", ""
					opts.Hooks, opts.MCP = nil, nil
					opts.SkillDirs = opts.SkillDirs[:len(opts.SkillDirs)-1]
					opts.AgentDirs = opts.AgentDirs[:len(opts.AgentDirs)-1]
					opts.CheckpointDir = filepath.Join(stateDir, "checkpoints")
					if workingSet > 0 {
						opts.WorkingSetTokens = workingSet
					}
					opts.NoHistoryNotes = opts.NoHistoryNotes || noHistoryNotes
					r := &direct.Runner{Gateway: ep.newGateway(sess.ID), Session: sess, Opts: opts}
					return r, func() { r.Close() }, nil
				}}
			if ep.provider == inference.ProviderLocal {
				dr.ServerBinary = app.serverBinary()
			}
			rep, err := dr.Run(ctx, ep.model, tasks, out)
			if rep != nil {
				md := strings.TrimSuffix(out, ".json") + ".md"
				var b bytes.Buffer
				_ = benchmark.WriteDirectMarkdown(&b, rep)
				_ = os.WriteFile(md, b.Bytes(), 0o644)
				_ = recordBenchmark(cmd, app, rep.ID, "direct", ep.model, dr.Settings, rep)
				s := rep.Summary
				app.printf("passed %d/%d (%.0f%%), %.1f model calls and %.1f tool calls per task, %.0f prompt tokens per task (%.0f%% from the cache), %.0fs/task\nreport: %s\n",
					s.Passed, s.Tasks, 100*s.PassRate, s.MeanCalls, s.MeanToolCalls, s.MeanPrompt, 100*s.CacheHitRate, s.MeanWallSeconds, md)
			}
			return err
		},
	}
	f := cmd.Flags()
	f.StringSliceVar(&dirs, "tasks", []string{"benchmarks/direct"}, "task definition directories")
	f.StringVar(&fixtures, "fixtures", "benchmarks/fixtures", "fixtures directory")
	f.StringSliceVar(&only, "only", nil, "task ids or categories to run")
	f.StringVar(&out, "out", "", "report path (.json; .md written alongside)")
	f.StringVarP(&modelName, "model", "m", "", "model profile (local) or model (cloud)")
	f.StringVar(&approval, "approval", direct.ApprovalAuto, "approval mode for the agent: ask|edits|auto")
	f.DurationVar(&timeout, "timeout", 20*time.Minute, "time limit per task when the task sets none")
	f.StringSliceVar(&compare, "compare", nil, "compare two saved reports (OLD.json,NEW.json) instead of running")
	f.IntVar(&workingSet, "working-set", 0, "history budget in tokens for this run (0 = direct.working_set_tokens)")
	f.BoolVar(&noHistoryNotes, "no-history-notes", false, "turn off history notes for this run (direct.history_notes)")
	return cmd
}

func newBenchIntelCmd(app *App) *cobra.Command {
	var dir, fixtures, out string
	var only []string
	cmd := &cobra.Command{
		Use:   "intel",
		Short: "Overlap study: ask Serena, codebase-memory-mcp and a grep baseline the same ground-truth navigation questions",
		RunE: func(cmd *cobra.Command, _ []string) error {
			ctx := cmd.Context()
			specs, err := benchmark.LoadIntelSpecs(dir)
			if err != nil {
				return err
			}
			if len(only) > 0 {
				var sel []benchmark.IntelSpec
				for _, s := range specs {
					if contains(only, s.ID) {
						sel = append(sel, s)
					}
				}
				specs = sel
			}
			work := filepath.Join(app.Paths.Cache, "bench-work")
			if err := os.MkdirAll(work, 0o700); err != nil {
				return err
			}
			study := &benchmark.IntelStudy{FixturesDir: fixtures, WorkRoot: work,
				Progress: func(s string) { fmt.Fprintf(app.Err, "%s %s\n", time.Now().Format("15:04:05"), s) },
				Serena: func(root string) *serena.Manager {
					m := app.serenaManager(app.Paths)
					m.Root, m.MaxInstances = root, 1
					return m
				},
				Graph: func(cacheDir string) *cbm.Client {
					return &cbm.Client{Binary: app.Config.RepoIntel.Binary, CacheDir: cacheDir}
				},
			}
			if err := study.Serena("").Verify(ctx); err != nil {
				return fmt.Errorf("serena: %w (run `"+buildinfo.Command()+" serena setup`)", err)
			}
			var reps []*benchmark.IntelReport
			for _, s := range specs {
				r, err := study.Run(ctx, s)
				if err != nil {
					return fmt.Errorf("%s: %w", s.ID, err)
				}
				reps = append(reps, r)
			}
			stamp := time.Now().UTC().Format("20060102T150405Z")
			if out == "" {
				out = filepath.Join("benchmarks", "reports", stamp+"-intel-overlap.json")
			}
			b, _ := json.MarshalIndent(reps, "", "  ")
			if err := config.WriteFileAtomic(out, b, 0o644); err != nil {
				return err
			}
			var md bytes.Buffer
			_ = benchmark.WriteIntelMarkdown(&md, reps)
			mdPath := strings.TrimSuffix(out, ".json") + ".md"
			if err := os.WriteFile(mdPath, md.Bytes(), 0o644); err != nil {
				return err
			}
			app.printf("%s\nreport: %s\n", md.String(), mdPath)
			return nil
		},
	}
	f := cmd.Flags()
	f.StringVar(&dir, "specs", "benchmarks/intel", "study definitions directory")
	f.StringVar(&fixtures, "fixtures", "benchmarks/fixtures", "fixtures directory")
	f.StringSliceVar(&only, "only", nil, "study ids to run")
	f.StringVar(&out, "out", "", "report path (.json; .md written alongside)")
	return cmd
}

func newBenchLeaseCmd(app *App) *cobra.Command {
	var repos []string
	var out string
	var commits, maxFiles int
	cmd := &cobra.Command{
		Use:   "lease",
		Short: "Score request-derived leases against real commits (precision and recall of the deriver)",
		Long: `For each recent commit of each repository, derive a lease (the
declarations, files and directories the request is about) from the commit
message against the parent's tree, and compare it with what the commit
changed outside tests. The message is scored as written and without its
"pkg/path:" prefix. No model is involved.`,
		RunE: func(cmd *cobra.Command, _ []string) error {
			if len(repos) == 0 {
				return fmt.Errorf("--repo is required (a git checkout; repeatable)")
			}
			var reps []*benchmark.LeaseReport
			for _, r := range repos {
				st := &benchmark.LeaseStudy{Repo: r, Commits: commits, MaxFiles: maxFiles,
					Progress: func(s string) { fmt.Fprintf(app.Err, "%s %s\n", time.Now().Format("15:04:05"), s) }}
				rep, err := st.Run(cmd.Context())
				if err != nil {
					return fmt.Errorf("%s: %w", r, err)
				}
				reps = append(reps, rep)
			}
			var md bytes.Buffer
			benchmark.WriteLeaseMarkdown(&md, reps)
			if out != "" {
				b, err := benchmark.MarshalLease(reps)
				if err != nil {
					return err
				}
				if err := config.WriteFileAtomic(out, b, 0o644); err != nil {
					return err
				}
				if err := os.WriteFile(strings.TrimSuffix(out, ".json")+".md", md.Bytes(), 0o644); err != nil {
					return err
				}
			}
			app.printf("%s", md.String())
			return nil
		},
	}
	f := cmd.Flags()
	f.StringSliceVar(&repos, "repo", nil, "git checkout to study (repeatable)")
	f.IntVar(&commits, "commits", 100, "commits per repository (the newest that change Go code)")
	f.IntVar(&maxFiles, "max-files", 30, "skip commits that change more non-test files than this")
	f.StringVar(&out, "out", "", "report path (.json; .md written alongside)")
	return cmd
}

func newBenchTrailCmd(app *App) *cobra.Command {
	var repos []string
	var out string
	var rev string
	var commits, history, maxFiles int
	cmd := &cobra.Command{
		Use:   "trail",
		Short: "Score whether a repository's history predicts the files a change needs",
		Long: `For each recent commit of each repository, suggest files from the
commits before it and compare them with what the commit changed outside
tests: at request time (the files the message names, those plus the files
most often changed with them, the most changed files overall) and at edit
time (for each changed file, the files usually changed with it). No model
is involved.`,
		RunE: func(cmd *cobra.Command, _ []string) error {
			if len(repos) == 0 {
				return fmt.Errorf("--repo is required (a git checkout; repeatable)")
			}
			var reps []*benchmark.TrailReport
			for _, r := range repos {
				st := &benchmark.TrailStudy{Repo: r, Rev: rev, Commits: commits, History: history, MaxFiles: maxFiles,
					Progress: func(s string) { fmt.Fprintf(app.Err, "%s %s\n", time.Now().Format("15:04:05"), s) }}
				rep, err := st.Run(cmd.Context())
				if err != nil {
					return fmt.Errorf("%s: %w", r, err)
				}
				reps = append(reps, rep)
			}
			var md bytes.Buffer
			benchmark.WriteTrailMarkdown(&md, reps)
			if out != "" {
				b, err := benchmark.MarshalTrail(reps)
				if err != nil {
					return err
				}
				if err := config.WriteFileAtomic(out, b, 0o644); err != nil {
					return err
				}
				if err := os.WriteFile(strings.TrimSuffix(out, ".json")+".md", md.Bytes(), 0o644); err != nil {
					return err
				}
			}
			app.printf("%s", md.String())
			return nil
		},
	}
	f := cmd.Flags()
	f.StringSliceVar(&repos, "repo", nil, "git checkout to study (repeatable)")
	f.IntVar(&commits, "commits", 100, "commits per repository (the newest that change Go code)")
	f.StringVar(&rev, "rev", "", "newest commit to consider (default HEAD); an older one holds out the newest commits")
	f.IntVar(&history, "history", 1000, "earlier commits that form each commit's trail")
	f.IntVar(&maxFiles, "max-files", 30, "skip commits that change more non-test files than this")
	f.StringVar(&out, "out", "", "report path (.json; .md written alongside)")
	return cmd
}

func newBenchCompareCmd(app *App) *cobra.Command {
	var base, cand []string
	cmd := &cobra.Command{
		Use:   "compare",
		Short: "Compare candidate runs of a suite with baseline runs (direct or bounded reports)",
		Long: `Each side is one or more saved reports of the same suite (bench direct or
bench tasks). A metric is called better or worse only when the candidate's
mean lies outside the range of the baseline's own runs; with one baseline run
the noise is unknown and nothing is called a difference. Per task, passes are
counted on each side.`,
		RunE: func(cmd *cobra.Command, _ []string) error {
			if len(base) == 0 || len(cand) == 0 {
				return fmt.Errorf("--base and --candidate each need at least one report")
			}
			load := func(paths []string) ([]*benchmark.Run, error) {
				var out []*benchmark.Run
				for _, p := range paths {
					r, err := benchmark.LoadRun(p)
					if err != nil {
						return nil, err
					}
					if len(out) > 0 && out[0].Kind != r.Kind {
						return nil, fmt.Errorf("%s is a %s report; %s is %s", p, r.Kind, paths[0], out[0].Kind)
					}
					out = append(out, r)
				}
				return out, nil
			}
			b, err := load(base)
			if err != nil {
				return err
			}
			c, err := load(cand)
			if err != nil {
				return err
			}
			if b[0].Kind != c[0].Kind {
				return fmt.Errorf("the baseline is %s and the candidate %s", b[0].Kind, c[0].Kind)
			}
			var buf bytes.Buffer
			benchmark.Compare(&buf, b, c)
			app.printf("%s", buf.String())
			return nil
		},
	}
	f := cmd.Flags()
	f.StringSliceVar(&base, "base", nil, "baseline report (repeatable)")
	f.StringSliceVar(&cand, "candidate", nil, "candidate report (repeatable)")
	return cmd
}
