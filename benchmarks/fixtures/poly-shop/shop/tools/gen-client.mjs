// Generates web/src/client.gen.ts from api/openapi.json: one interface per
// component schema, a list of each schema's fields, and a fetch function per
// operation. --check exits 1 when the checked-in file differs.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const spec = JSON.parse(readFileSync(join(root, 'api/openapi.json'), 'utf8'));
const out = join(root, 'web/src/client.gen.ts');

const tsType = (p) => {
  if (p.$ref) return p.$ref.split('/').pop();
  switch (p.type) {
    case 'integer':
    case 'number':
      return 'number';
    case 'string':
      return p.enum ? p.enum.map((e) => JSON.stringify(e)).join(' | ') : 'string';
    case 'boolean':
      return 'boolean';
    case 'array':
      return tsType(p.items) + '[]';
    default:
      return 'unknown';
  }
};

let src = '// Code generated by tools/gen-client.mjs from api/openapi.json. DO NOT EDIT.\n\n';
for (const [name, s] of Object.entries(spec.components.schemas)) {
  const req = new Set(s.required || []);
  src += `export interface ${name} {\n`;
  for (const [f, p] of Object.entries(s.properties)) src += `  ${f}${req.has(f) ? '' : '?'}: ${tsType(p)};\n`;
  src += '}\n\n';
  src += `export const ${name.toUpperCase()}_FIELDS = ${JSON.stringify(Object.keys(s.properties))} as const;\n\n`;
}
for (const [path, ops] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(ops)) {
    const ret = tsType(op.responses['200'].content['application/json'].schema);
    const params = (op.parameters || []).map((p) => p.name);
    const url = '`${base}' + path.replace(/\{(\w+)\}/g, '${encodeURIComponent($1)}') + '`';
    src += `export async function ${op.operationId}(base: string, ${params.map((p) => p + ': string').join(', ')}): Promise<${ret}> {\n`;
    src += `  const res = await fetch(${url}, { method: '${method.toUpperCase()}' });\n`;
    src += `  if (!res.ok) throw new Error(\`${op.operationId}: HTTP \${res.status}\`);\n`;
    src += `  return (await res.json()) as ${ret};\n}\n`;
  }
}

if (process.argv.includes('--check')) {
  const have = readFileSync(out, 'utf8');
  if (have !== src) {
    console.error('web/src/client.gen.ts is stale: run node tools/gen-client.mjs');
    process.exit(1);
  }
  console.log('client.gen.ts is current');
} else {
  writeFileSync(out, src);
  console.log('wrote web/src/client.gen.ts');
}
